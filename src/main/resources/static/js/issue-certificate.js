initLayout("issue", { adminOnly: true });

let courses = [];
let participants = [];

async function loadOptions() {
  try {
    courses = await CoursesAPI.getAll();
    participants = await ParticipantsAPI.getAll();
    
    const cSel = document.getElementById("course-select");
    cSel.innerHTML = '<option value="">-- Select a Course --</option>' + courses.map(c => `<option value="${c.id}">${escHtml(c.title)}</option>`).join("");
    
    const pSel = document.getElementById("participant-select");
    pSel.innerHTML = '<option value="">-- Select a Participant --</option>' + participants.map(p => `<option value="${p.id}">${escHtml(p.fullName)}</option>`).join("");
  } catch (err) {
    Toast.error(err.message);
  }
}

document.getElementById("course-select")?.addEventListener("change", (e) => {
  const c = courses.find(x => x.id == e.target.value);
  document.getElementById("prev-course").textContent = c ? c.title : "Select a course...";
});

document.getElementById("participant-select")?.addEventListener("change", (e) => {
  const p = participants.find(x => x.id == e.target.value);
  document.getElementById("prev-name").textContent = p ? p.fullName : "Alex Morgan";
});

document.getElementById("custom-id")?.addEventListener("input", (e) => {
  document.getElementById("prev-id").textContent = e.target.value.trim() || "Enter certificate ID";
});

document.getElementById("issue-form")?.addEventListener("submit", async (e) => {
  e.preventDefault();
  const cid = document.getElementById("course-select").value;
  const pid = document.getElementById("participant-select").value;
  const custom = document.getElementById("custom-id").value.trim();
  
  if (!cid || !pid) return Toast.error("Please select a course and a participant.");
  if (!custom) return Toast.error("Please enter a certificate ID, e.g. CRT-2026-001.");
  
  const btn = document.getElementById("issue-btn");
  btn.disabled = true;
  btn.innerHTML = '<div class="spinner spinner-sm"></div>';
  
  try {
    const res = await CertificatesAPI.issue({ courseId: parseInt(cid), participantId: parseInt(pid), customCertificateId: custom });
    
    Toast.success("Certificate issued successfully.");
    
    document.getElementById("issue-form").classList.add("hidden");
    document.getElementById("success-view").classList.remove("hidden");
    
    document.getElementById("prev-id").textContent = res.certificateId;
    document.getElementById("prev-code").textContent = res.verificationCode;
    
    document.getElementById("btn-view-cert").href = "certificates.html?view=" + encodeURIComponent(res.certificateId);
    
  } catch (err) { Toast.error(err.message); }
  finally { btn.disabled = false; btn.innerHTML = '<i class="fa-solid fa-bolt"></i> Generate Credential'; }
});

window.resetForm = function() {
  document.getElementById("issue-form").reset();
  document.getElementById("success-view").classList.add("hidden");
  document.getElementById("issue-form").classList.remove("hidden");
  
  document.getElementById("prev-course").textContent = "Select a course...";
  document.getElementById("prev-name").textContent = "Alex Morgan";
  document.getElementById("prev-id").textContent = "Enter certificate ID";
  document.getElementById("prev-code").textContent = "Generated by server";
}


loadOptions();
